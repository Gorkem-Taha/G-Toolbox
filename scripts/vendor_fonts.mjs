// Vendors the Inter and JetBrains Mono web fonts (latin + latin-ext, which covers
// Turkish) from pinned @fontsource packages, replacing the Google Fonts @import.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dst = "static/vendor/fonts";
const families = [
  { pkg: "@fontsource/inter", weights: [300, 400, 500, 600, 700, 800] },
  { pkg: "@fontsource/jetbrains-mono", weights: [400, 500] },
];
rmSync(dst, { recursive: true, force: true });
mkdirSync(join(dst, "files"), { recursive: true });

let out = "/* Generated by scripts/vendor_fonts.mjs — do not edit. Fonts: SIL Open Font License 1.1 */\n";
for (const { pkg, weights } of families) {
  const base = join("node_modules", pkg);
  for (const w of weights) {
    const css = readFileSync(join(base, `${w}.css`), "utf8");
    for (const block of css.split(/(?=\/\* )/)) {
      if (!/-(latin|latin-ext)-\d+-normal \*\//.test(block)) continue;
      const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      cpSync(join(base, "files", file), join(dst, "files", file));
      out += block
        .replace(/src: [^;]+;/, `src: url(./files/${file}) format('woff2');`)
        .trim() + "\n";
    }
  }
  cpSync(join(base, "LICENSE"), join(dst, `LICENSE-${pkg.split("/")[1]}.txt`));
}
writeFileSync(join(dst, "fonts.css"), out);
console.log("Fonts vendored to", dst);
